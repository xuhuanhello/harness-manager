export type MessageCode = keyof typeof MESSAGES;
type Args<C extends MessageCode> = Parameters<(typeof MESSAGES)[C]>;

export function message<C extends MessageCode>(code: C, ...args: Args<C>): string {
  return (MESSAGES[code] as (...values: Args<C>) => string)(...args);
}

export function appError<C extends MessageCode>(code: C, ...args: Args<C>): AppError {
  return new AppError(code, message(code, ...args));
}
